# image.py out armgba-boot.h: writes the boot ROMs in out/ as C arrays, the Game Boy Color's and
# Game Boy Advance's padded to 2,304 bytes ($0100-$01FF unused: the cartridge shows there).
import sys

sizes = {'dmg': 256, 'mgb': 256, 'cgb': 2304, 'agb': 2304}
lines = ["// Generated by gbboot/build.sh from the sources in gbboot/. Don't edit.", '']
for name, size in sizes.items():
    data = open('%s/%s.bin' % (sys.argv[1], name), 'rb').read()
    if len(data) > size:
        sys.exit('%s is %d bytes, over %d' % (name, len(data), size))
    data = data.ljust(size, b'\0')
    lines.append('static const unsigned char armgba_%s_boot[%d] = {' % (name, size))
    for i in range(0, size, 16):
        lines.append('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('')
open(sys.argv[2], 'w').write('\n'.join(lines))
